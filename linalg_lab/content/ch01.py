    R = np.array(A, dtype=float, copy=True)
    m, n = R.shape
    pivots = []
    row = 0
    for col in range(n):
        if row == m:
            break
        pivot = row + int(np.argmax(np.abs(R[row:, col])))
        if abs(R[pivot, col]) <= 1e-10:
            continue
        R[[row, pivot]] = R[[pivot, row]]
        R[row] /= R[row, col]
        for i in range(m):
            if i != row:
                R[i] -= R[i, col] * R[row]
        pivots.append(col)
        row += 1
    return (len(pivots) < n, np.array(pivots, dtype=int))
